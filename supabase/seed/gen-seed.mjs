// Generates supabase/migrations/0002_seed.sql from exercises.mjs.  Run: node supabase/seed/gen-seed.mjs
// The data is embedded as JSON and unpacked in SQL, keeping the migration compact.
import { writeFileSync } from 'node:fs'
import { EQUIPMENT, MUSCLE_GROUPS, EXERCISES } from './exercises.mjs'

const json = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
const names = EXERCISES.map((e) => e[0].toLowerCase())
if (new Set(names).size !== names.length) throw new Error('duplicate exercise name')

const sql = `-- Generated by supabase/seed/gen-seed.mjs. Do not edit by hand.
insert into public.muscle_groups (slug, name, parent_slug, sort)
  select x->>0, x->>1, x->>2, (x->>3)::int from jsonb_array_elements(${json(MUSCLE_GROUPS)}) x;
insert into public.equipment (slug, name, home)
  select x->>0, x->>1, (x->>2)::bool from jsonb_array_elements(${json(EQUIPMENT)}) x;
do $$ declare x jsonb; eid uuid; home text[] := array(select slug from public.equipment where home); begin
for x in select * from jsonb_array_elements(${json(EXERCISES)}) loop
 insert into public.exercises (slug, name, classification, difficulty, description, instructions, common_mistakes,
   secondary_muscles, rec_sets, rec_reps, rest_seconds, environments, image_id)
 values (trim(both '-' from regexp_replace(lower(x->>0), '[^a-z0-9]+', '-', 'g')), x->>0, x->>2, x->>4, x->>10,
   array(select jsonb_array_elements_text(x->11)), array(select jsonb_array_elements_text(x->12)),
   array(select jsonb_array_elements_text(x->8)), (x->>5)::int, x->>6, (x->>7)::int,
   case when array(select jsonb_array_elements_text(x->3)) <@ home then array['home','gym'] else array['gym'] end,
   x->>9)
 returning id into eid;
 insert into public.exercise_muscles select eid, g from jsonb_array_elements_text(x->1) g;
 insert into public.exercise_equipment select eid, g from jsonb_array_elements_text(x->3) g;
end loop; end $$;
`
writeFileSync(new URL('../migrations/0002_seed.sql', import.meta.url), sql)
console.log(`seeded ${EXERCISES.length} exercises (${sql.length} bytes)`)
